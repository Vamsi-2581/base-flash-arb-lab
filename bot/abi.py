"""Tiny static-ABI encoder for fixed EVM calls, without web3 dependencies.

Selectors generated by reference Keccak-256 (not NIST SHA3-256).
"""
from __future__ import annotations

MASK = (1 << 64) - 1
ROT = (
    (0, 36, 3, 41, 18), (1, 44, 10, 45, 2), (62, 6, 43, 15, 61),
    (28, 55, 25, 21, 56), (27, 20, 39, 8, 14),
)
RC = (
    0x0000000000000001, 0x0000000000008082, 0x800000000000808A,
    0x8000000080008000, 0x000000000000808B, 0x0000000080000001,
    0x8000000080008081, 0x8000000000008009, 0x000000000000008A,
    0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
    0x000000008000808B, 0x800000000000008B, 0x8000000000008089,
    0x8000000000008003, 0x8000000000008002, 0x8000000000000080,
    0x000000000000800A, 0x800000008000000A, 0x8000000080008081,
    0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
)


def _rol(v: int, r: int) -> int:
    return ((v << r) | (v >> (64 - r))) & MASK if r else v


def keccak256(data: bytes) -> bytes:
    rate = 136  # Keccak-256
    pad = bytearray(data) + b"\x01"
    pad.extend(b"\x00" * ((-len(pad)) % rate))
    pad[-1] |= 0x80
    s = [0] * 25
    for start in range(0, len(pad), rate):
        block = pad[start:start + rate]
        for i in range(rate // 8):
            s[i] ^= int.from_bytes(block[i*8:(i+1)*8], "little")
        for rc in RC:
            c = [s[x] ^ s[x+5] ^ s[x+10] ^ s[x+15] ^ s[x+20] for x in range(5)]
            d = [c[(x-1) % 5] ^ _rol(c[(x+1) % 5], 1) for x in range(5)]
            for x in range(5):
                for y in range(5):
                    s[x+5*y] ^= d[x]
            b = [0] * 25
            for x in range(5):
                for y in range(5):
                    b[y+5*((2*x+3*y) % 5)] = _rol(s[x+5*y], ROT[x][y])
            for x in range(5):
                for y in range(5):
                    s[x+5*y] = b[x+5*y] ^ ((~b[(x+1) % 5+5*y]) & b[(x+2) % 5+5*y])
            s[0] ^= rc
    return b"".join(s[i].to_bytes(8, "little") for i in range(rate//8))[:32]


def selector(signature: str) -> str:
    return keccak256(signature.encode("ascii"))[:4].hex()


def word(value: int | str) -> str:
    if isinstance(value, str):
        if not value.startswith("0x") or len(value) != 42:
            raise ValueError(f"Expected address, got {value!r}")
        value = int(value[2:], 16)
    if not 0 <= value < (1 << 256):
        raise ValueError("Value outside uint256")
    return f"{value:064x}"


def encode(signature: str, *args: int | str) -> str:
    return "0x" + selector(signature) + "".join(word(a) for a in args)


def result_uint(raw: str, position: int = 0) -> int:
    h = raw.removeprefix("0x")
    if len(h) < (position + 1) * 64:
        raise ValueError("Short ABI result")
    return int(h[position*64:(position+1)*64], 16)


def result_address(raw: str) -> str:
    h = raw.removeprefix("0x")
    if len(h) < 64:
        raise ValueError("Short ABI address result")
    return "0x" + h[24:64]


